import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';

/** Files in public/ the app needs offline (the build bundle does not list them). */
const PUBLIC_FILES = [
  'favicon.svg',
  'manifest.webmanifest',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'icons/apple-touch-icon.png',
];

/**
 * What to cache on install: the page (as "/"), every built file except source maps and the
 * older `.woff` fonts that browsers with service workers never ask for, and the public files.
 */
export function precacheList(bundleFiles: string[]): string[] {
  const built = bundleFiles.filter(
    (f) => f !== 'index.html' && !f.endsWith('.map') && !f.endsWith('.woff'),
  );
  return ['/', ...[...built, ...PUBLIC_FILES].sort().map((f) => `/${f}`)];
}

/**
 * The service worker. Pages come from the network first, so a new release shows at once, and
 * from the cache when offline; built files come from the cache first, since their names change
 * whenever their content does. The API is never cached: saving and sharing need the server.
 */
export function workerSource(precache: string[]): string {
  const version = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 12);
  return `// Generated by apps/web/build/service-worker.ts
const CACHE = 'bg3planner-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((k) => k.startsWith('bg3planner-') && k !== CACHE).map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== location.origin) return;
  if (url.pathname.startsWith('/api/')) return;
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() =>
        caches.match('/', { cacheName: CACHE }).then((page) => page || Response.error()),
      ),
    );
    return;
  }
  event.respondWith(caches.match(request).then((cached) => cached || fetch(request)));
});
`;
}

/** Emits sw.js with this build's files. */
export function serviceWorker(): Plugin {
  return {
    name: 'bg3planner-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: workerSource(precacheList(Object.keys(bundle))),
      });
    },
  };
}
